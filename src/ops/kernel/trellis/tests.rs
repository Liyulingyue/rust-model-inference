#[cfg(feature = "vulkan")]
#[test]
#[ignore = "requires a Vulkan device"]
fn vulkan_trellis_frequency_bands_match_cpu_across_scratch_chunks() {
    use crate::vulkan::ops::{ArenaRegion, Qwen3Ops, TokenCommands};
    use crate::vulkan::qwen3::UploadedBuffers;
    let context = crate::ops::float::shared_vulkan_context().unwrap();
    let mut src = Fixture::default();
    for (i, bits) in [1, 2, 3, 4, 5, 6].into_iter().enumerate() {
        let name = format!("output.band{i:02}");
        src.band(&name, bits, if i % 2 == 0 { 16 } else { 1 });
        src.permute(&format!("{name}.trellis_pin"), 32, 5);
        src.permute(&format!("{name}.trellis_pout"), 32, 7);
    }
    let n = 6 * 32;
    src.meta
        .insert("trellis.lm_head_bands".into(), MetaValue::Uint32(6));
    src.permute("output.vocab_gather", n, 11);
    let w = load_weight(&src, "output.weight", 32, n).unwrap();
    let rows = 11;
    let x: Vec<_> = (0..rows * 32)
        .map(|i| (i as f32 % 47.0 - 13.0) / 17.0)
        .collect();
    let expected: Vec<_> = x.chunks_exact(32).flat_map(|row| w.matmul(row)).collect();
    let input = ArenaRegion {
        offset: 0,
        size: x.len() * 4,
    };
    let output = ArenaRegion {
        offset: input.end(),
        size: expected.len() * 4,
    };
    let mut buffers = UploadedBuffers::new(context);
    let mut ops = Qwen3Ops::new_with_size(context, output.end(), 8).unwrap();
    let bindings = ops
        .bind_trellis(&mut buffers, w.kernel.trellis().unwrap())
        .unwrap();
    ops.write_f32(input, &x).unwrap();
    let cmd = TokenCommands::begin(context).unwrap();
    let before = context.submission_count();
    ops.record_weight_matmul_rows(
        &cmd,
        bindings,
        input,
        input,
        input,
        input,
        input,
        input,
        &[(output, n, n * 4)],
        32,
        rows,
        32,
    )
    .unwrap();
    cmd.submit_and_wait().unwrap();
    assert!(context.submission_count() > before);
    let values = ops.read_f32(output, expected.len()).unwrap();
    let max_abs = expected
        .iter()
        .zip(values)
        .map(|(a, b)| (a - b).abs())
        .fold(0.0f32, f32::max);
    eprintln!(
        "device={} rows={rows} bands=6 max_abs={max_abs}",
        context.device_name()
    );
    assert!(values.iter().all(|x| x.is_finite()) && max_abs < 5e-4);
}
