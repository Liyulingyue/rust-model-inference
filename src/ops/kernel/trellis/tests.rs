use super::*;
use crate::core::tensor::{GGMLType, MetaValue, MetaValueType, TensorInfo, TensorSource};
use std::collections::HashMap;

#[derive(Default)]
struct Fixture {
    meta: HashMap<String, MetaValue>,
    tensors: HashMap<String, (TensorInfo, Vec<u8>)>,
}

impl TensorSource for Fixture {
    fn metadata(&self, name: &str) -> Option<&MetaValue> {
        self.meta.get(name)
    }
    fn tensor_info(&self, name: &str) -> Option<&TensorInfo> {
        Some(&self.tensors.get(name)?.0)
    }
    fn tensor_slice(&self, name: &str) -> Option<&[u8]> {
        Some(&self.tensors.get(name)?.1)
    }
}

impl Fixture {
    fn put(&mut self, name: &str, dims: &[u64], ty: GGMLType, data: Vec<u8>) {
        self.tensors.insert(
            name.into(),
            (
                TensorInfo {
                    name: name.into(),
                    dims: dims.to_vec(),
                    ggml_type: ty,
                    offset: 0,
                },
                data,
            ),
        );
    }

    fn band(&mut self, base: &str, bits: usize, out_block: i32) {
        self.meta
            .insert("trellis.version".into(), MetaValue::Uint32(1));
        self.meta.insert(
            format!("trellis.desc.{base}"),
            MetaValue::Array(
                MetaValueType::Int32,
                [i32::from(out_block != 1), out_block, 1, 1, 16, 1, 1, 32]
                    .map(MetaValue::Int32)
                    .to_vec(),
            ),
        );
        self.put(
            &format!("{base}.weight"),
            &[32, 32],
            GGMLType::from_i32(43 + bits as i32).unwrap(),
            code_bytes(bits),
        );
        self.put(
            &format!("{base}.trellis_s16"),
            &[2],
            GGMLType::F16,
            vec![0, 0x38, 0, 0x40],
        );
        let scale: Vec<u8> = (0..32)
            .flat_map(|i| ((i as f32 - 10.0) / 16.0).to_le_bytes())
            .collect();
        for suffix in ["pre", "post"] {
            self.put(
                &format!("{base}.trellis_{suffix}"),
                &[32],
                GGMLType::F32,
                scale.clone(),
            );
        }
    }

    fn permute(&mut self, name: &str, n: usize, step: usize) {
        self.put(
            name,
            &[n as u64],
            GGMLType::I32,
            (0..n)
                .flat_map(|i| ((i * step % n) as u32).to_le_bytes())
                .collect(),
        );
    }
}

fn code_bytes(bits: usize) -> Vec<u8> {
    (0..128 * bits).map(|i| (71 * i + 13) as u8).collect()
}

#[test]
fn circular_tiles_match_the_pinned_integer_decoder_at_all_six_widths() {
    // FNV-1a over row-major signed grid bytes from ggml_trellis_decode_rows
    // at Nari Labs 2644f7de, for the four tiles generated by code_bytes.
    let oracle = [
        0xeff9c80d, 0xe5abbdcd, 0xa97c1c47, 0x456c5f09, 0x36804118, 0x98fd374d,
    ];
    for (i, expected) in oracle.into_iter().enumerate() {
        let bits = i + 1;
        let codes = code_bytes(bits);
        let mut hash = 2166136261u32;
        for row in 0..32 {
            let mut decoded = [0.0; 32];
            decode::embedding_row(
                &codes[(row / 16) * 64 * bits..][..64 * bits],
                bits,
                row % 16,
                &[1.0, 1.0],
                &mut decoded,
            );
            for v in decoded {
                hash = (hash ^ u32::from(v as i8 as u8)).wrapping_mul(16777619);
            }
        }
        assert_eq!(hash, expected, "TRL{bits}");
    }
}

#[test]
fn native_dot_matches_decoded_rows_at_every_bit_width() {
    for bits in 1..=6 {
        let codes = code_bytes(bits);
        let x: Vec<_> = (0..32).map(|i| (i as f32 - 12.0) * 0.031).collect();
        for bytes in codes.chunks_exact(64 * bits) {
            let mut y = [0.0; 16];
            decode::dot16(bytes, bits, &x, &mut y);
            for (row, v) in y.into_iter().enumerate() {
                let mut w = [0.0; 32];
                decode::embedding_row(bytes, bits, row, &[1.0, 1.0], &mut w);
                let reference: f64 = w
                    .iter()
                    .zip(&x)
                    .map(|(&a, &b)| f64::from(a) * f64::from(b))
                    .sum();
                assert!(
                    (f64::from(v) - reference).abs() < 1e-4,
                    "TRL{bits} row {row}"
                );
            }
        }
    }
}

#[test]
fn frequency_bands_compose_output_gathers_and_reject_duplicate_indices() {
    let mut src = Fixture::default();
    for (i, bits) in [2, 5].into_iter().enumerate() {
        let base = format!("output.band{i:02}");
        src.band(&base, bits, 16);
        src.permute(&format!("{base}.trellis_pin"), 32, 5);
        src.permute(&format!("{base}.trellis_pout"), 32, 7);
    }
    src.meta
        .insert("trellis.lm_head_bands".into(), MetaValue::Uint32(2));
    src.permute("output.vocab_gather", 64, 9);
    let x: Vec<_> = (0..32).map(|i| (i as f32 - 17.0) / 32.0).collect();
    let out = {
        let w = load_weight(&src, "output.weight", 32, 64).unwrap();
        let mut out = vec![f32::NAN; 64];
        for thread in 0..3 {
            let mut part = vec![f32::NAN; 64];
            w.kernel
                .forward_prepared(&x, &[], &[], None, &mut part, 32, 64, thread, 3);
            let owned = thread * 22..((thread + 1) * 22).min(64);
            for (row, value) in part.into_iter().enumerate() {
                assert_eq!(
                    value.is_finite(),
                    owned.contains(&row),
                    "worker {thread}, row {row}"
                );
                if owned.contains(&row) {
                    out[row] = value;
                }
            }
        }
        out
    };
    for i in 0..2 {
        let base = format!("output.band{i:02}.weight");
        let band = load_weight(&src, &base, 32, 32).unwrap().matmul(&x);
        for token in 0..64 {
            let stored = (token * 9) % 64;
            if stored / 32 == i {
                assert!((out[token] - band[stored % 32]).abs() < 1e-5);
            }
        }
    }
    src.permute("output.vocab_gather", 64, 2);
    assert!(load_weight(&src, "output.weight", 32, 64)
        .err()
        .unwrap()
        .contains("not a permutation"));
    src.meta
        .insert("trellis.version".into(), MetaValue::Int32(1));
    assert!(load_weight(&src, "output.weight", 32, 64)
        .err()
        .unwrap()
        .contains("UINT32"));
}

#[test]
fn embedding_uses_band_local_row_and_requires_all_side_tensors() {
    let mut src = Fixture::default();
    src.band("token_embd.band00", 1, 1);
    src.band("token_embd.band01", 4, 1);
    src.meta
        .insert("trellis.embed_bands".into(), MetaValue::Uint32(2));
    src.permute("token_embd.vocab_gather", 64, 3);
    {
        let emb = load_weight(&src, "token_embd.weight", 32, 64).unwrap();
        for token in [0, 15, 16, 31, 32, 63] {
            let stored = token * 3 % 64;
            let single = load_weight(
                &src,
                &format!("token_embd.band{:02}.weight", stored / 32),
                32,
                32,
            )
            .unwrap();
            let (mut got, mut expected) = ([0.0; 32], [0.0; 32]);
            emb.embedding_lookup(token, &mut got);
            single.embedding_lookup(stored % 32, &mut expected);
            assert!(got.iter().zip(expected).all(|(a, b)| (a - b).abs() < 1e-6));
        }
    }
    src.tensors.remove("token_embd.band01.trellis_s16");
    assert!(load_weight(&src, "token_embd.weight", 32, 64)
        .err()
        .unwrap()
        .contains("band01.trellis_s16"));
}

