//! Macros that emit AVX-512F (zmm) packed-weight matmul kernels.
//!
//! The zmm sibling of `simd_avx2.rs`: the same FMA skeleton widened to 16
//! lanes per vector (64 lanes per outer iteration via two accumulators),
//! with the per-(row, token) tail falling back to scalar FMA into the first
//! accumulator.  Each caller plugs in its own unpack helpers:
//!
//! * BF16: `_mm512_cvtepu16_epi32` + `_mm512_slli_epi32` (u16→f32 via shift,
//!   needs AVX-512BW)
//! * F16 : two F16C `_mm256_cvtph_ps` halves merged with `vinsertf64x4`
//! * F32 : `_mm512_loadu_ps` (no-op)
//!
//! Dispatch sites gate on `n_in % 16 == 0` so the scalar tail is a safety
//! net for direct callers (tests) rather than a production path; the AVX2
//! kernel keeps shapes that are multiples of 8 but not 16.

#![cfg(target_arch = "x86_64")]

use std::arch::x86_64::__m512;

#[inline(always)]
pub unsafe fn hsum512(v: __m512) -> f32 {
    use std::arch::x86_64::*;
    let lo = _mm512_castps512_ps256(v);
    let hi = _mm256_castpd_ps(_mm512_extractf64x4_pd(_mm512_castps_pd(v), 1));
    let s = _mm256_add_ps(lo, hi);
    crate::ops::kernel::simd_avx2::hsum256(s)
}

/// Emit an AVX-512F packed matmul kernel (zmm, 16 lanes per vector).
///
/// The caller supplies unpack helpers as standalone `unsafe` functions
/// (not macros):
///
/// `$unpack_16(w, r, c) -> __m512`    — load 16 weight lanes starting at
///   `(r, c)` and return them as 16 f32 lanes in a `__m512`.
/// `$scalar_unpack(w, r, c) -> f32`   — read a single weight lane as f32.
///
/// The accumulation shape (two zmm accumulators covering even/odd 16-lane
/// chunks, then a scalar tail folding into the first accumulator) is the
/// contract the tiled sibling reproduces verbatim.
#[macro_export]
macro_rules! avx512_matmul_packed {
    (
        $fn_name:ident,
        $bytes_per_element:expr,
        $unpack_16:path,
        $scalar_unpack:path
    ) => {
        /// AVX-512F packed-weight × F32-input matmul.  Generated by
        /// [`avx512_matmul_packed`].
        #[target_feature(enable = "avx512f", enable = "fma")]
        pub unsafe fn $fn_name(
            weight: &[u8],
            input: &[f32],
            output: &mut [f32],
            n_in: usize,
            row_start: usize,
            row_end: usize,
        ) {
            use ::std::arch::x86_64::*;
            let w_ptr = weight.as_ptr();
            let i_ptr = input.as_ptr();
            let out_ptr = output.as_mut_ptr();

            let mut out_local = 0usize;
            for row in row_start..row_end {
                let row_byte = row * n_in * $bytes_per_element;
                let mut acc0 = _mm512_setzero_ps();
                let mut acc1 = _mm512_setzero_ps();

                let mut i = 0;
                while i + 32 <= n_in {
                    let w_lo = $unpack_16(w_ptr, row_byte, i);
                    let w_hi = $unpack_16(w_ptr, row_byte, i + 16);
                    let x_lo = _mm512_loadu_ps(i_ptr.add(i));
                    let x_hi = _mm512_loadu_ps(i_ptr.add(i + 16));
                    acc0 = _mm512_fmadd_ps(w_lo, x_lo, acc0);
                    acc1 = _mm512_fmadd_ps(w_hi, x_hi, acc1);
                    i += 32;
                }
                while i + 16 <= n_in {
                    let w_f = $unpack_16(w_ptr, row_byte, i);
                    let x_f = _mm512_loadu_ps(i_ptr.add(i));
                    acc0 = _mm512_fmadd_ps(w_f, x_f, acc0);
                    i += 16;
                }
                // Scalar tail: a lane-wide FMA into the accumulator would be
                // counted once per lane by the horizontal sum, so the tail
                // keeps its own accumulator instead.
                let mut tail_sum = 0.0f32;
                while i < n_in {
                    let w_val = $scalar_unpack(w_ptr, row_byte, i);
                    let x_val = *i_ptr.add(i);
                    tail_sum = w_val.mul_add(x_val, tail_sum);
                    i += 1;
                }

                let total = unsafe {
                    $crate::ops::kernel::simd_avx512::hsum512(acc0)
                        + $crate::ops::kernel::simd_avx512::hsum512(acc1)
                } + tail_sum;
                *out_ptr.add(out_local) = total;
                out_local += 1;
            }
        }
    };
}

/// Emit the token-tiled sibling of [`avx512_matmul_packed`]: the dot body
/// above, verbatim, nested inside `(row-tile × token-tile)` blocking so the
/// weight panel and the input panel stay resident in L2 across the inner
/// loops.  Per-(row, token) values are bit-identical to the per-token
/// kernel; only the loop nesting changes.
#[macro_export]
macro_rules! avx512_matmul_packed_tiled {
    (
        $fn_name:ident,
        $bytes_per_element:expr,
        $unpack_16:path,
        $scalar_unpack:path
    ) => {
        /// Row-partitioned, token-tiled batched matmul over `n_tokens`
        /// activation rows. See [`avx512_matmul_packed`] for the dot
        /// contract.
        #[target_feature(enable = "avx512f", enable = "fma")]
        pub unsafe fn $fn_name(
            weight: &[u8],
            input: &[f32],
            output: &mut [f32],
            n_in: usize,
            n_out: usize,
            n_tokens: usize,
            row_start: usize,
            row_end: usize,
        ) {
            use ::std::arch::x86_64::*;
            const ROW_TILE: usize = 32;
            const TOKEN_TILE: usize = 32;
            let w_ptr = weight.as_ptr();
            let out_ptr = output.as_mut_ptr();

            let mut row_tile = row_start;
            while row_tile < row_end {
                let row_stop = (row_tile + ROW_TILE).min(row_end);
                let mut token_tile = 0usize;
                while token_tile < n_tokens {
                    let token_stop = (token_tile + TOKEN_TILE).min(n_tokens);
                    for row in row_tile..row_stop {
                        let row_byte = row * n_in * $bytes_per_element;
                        let out_row = out_ptr.add(row);
                        for token in token_tile..token_stop {
                            let i_ptr = input.as_ptr().add(token * n_in);
                            let mut acc0 = _mm512_setzero_ps();
                            let mut acc1 = _mm512_setzero_ps();

                            let mut i = 0;
                            while i + 32 <= n_in {
                                let w_lo = $unpack_16(w_ptr, row_byte, i);
                                let w_hi = $unpack_16(w_ptr, row_byte, i + 16);
                                let x_lo = _mm512_loadu_ps(i_ptr.add(i));
                                let x_hi = _mm512_loadu_ps(i_ptr.add(i + 16));
                                acc0 = _mm512_fmadd_ps(w_lo, x_lo, acc0);
                                acc1 = _mm512_fmadd_ps(w_hi, x_hi, acc1);
                                i += 32;
                            }
                            while i + 16 <= n_in {
                                let w_f = $unpack_16(w_ptr, row_byte, i);
                                let x_f = _mm512_loadu_ps(i_ptr.add(i));
                                acc0 = _mm512_fmadd_ps(w_f, x_f, acc0);
                                i += 16;
                            }
                            // Scalar tail: same separate accumulator as the
                            // per-token kernel (see the comment there).
                            let mut tail_sum = 0.0f32;
                            while i < n_in {
                                let w_val = $scalar_unpack(w_ptr, row_byte, i);
                                let x_val = *i_ptr.add(i);
                                tail_sum = w_val.mul_add(x_val, tail_sum);
                                i += 1;
                            }

                            let total = unsafe {
                                $crate::ops::kernel::simd_avx512::hsum512(acc0)
                                    + $crate::ops::kernel::simd_avx512::hsum512(acc1)
                            } + tail_sum;
                            *out_row.add(token * n_out) = total;
                        }
                    }
                    token_tile = token_stop;
                }
                row_tile = row_stop;
            }
        }
    };
}
