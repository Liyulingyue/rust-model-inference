pub(super) fn torch28_mel_filterbank() -> Vec<f32> {
    let mut filterbank = vec![0.0f32; MEL_BINS * FFT_BINS];
    let mut source = 0;
    for (row, &(start, end)) in ROW_RANGES.iter().enumerate() {
        let count = end - start;
        for (target, &bits) in filterbank[row * FFT_BINS + start..row * FFT_BINS + end]
            .iter_mut()
            .zip(&NONZERO_BITS[source..source + count])
        {
            *target = f32::from_bits(bits);
        }
        source += count;
    }
    debug_assert_eq!(source, NONZERO_BITS.len());
    filterbank
}
