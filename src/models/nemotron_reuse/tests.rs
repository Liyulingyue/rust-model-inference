#[test]
fn contracts_and_config_pin_the_published_architecture() {
    let mut config: serde_json::Value = serde_json::from_str(CONFIG).unwrap();
    assert!(validate_config(&config).is_ok());
    config["model_cfg"]["d_state"] = 32.into();
    assert!(validate_config(&config).is_err());
    assert!(validate_config(&serde_json::json!({"model_type":"qwen3"})).is_err());
    let shapes = contracts();
    assert_eq!(shapes.len(), 1416);
    assert_eq!(
        shapes
            .iter()
            .map(|(n, _)| n)
            .collect::<std::collections::HashSet<_>>()
            .len(),
        shapes.len()
    );
    assert!(Model::validate_compute(ComputePolicy::Vulkan)
        .unwrap_err()
        .contains("no Vulkan"));
    assert!(Model::validate_compute(ComputePolicy::Auto).is_ok());
}

struct Source {
    info: TensorInfo,
    bytes: Vec<u8>,
}
impl TensorSource for Source {
    fn metadata(&self, _: &str) -> Option<&MetaValue> {
        None
    }
    fn tensor_info(&self, name: &str) -> Option<&TensorInfo> {
        (name == self.info.name).then_some(&self.info)
    }
    fn tensor_slice(&self, name: &str) -> Option<&[u8]> {
        (name == self.info.name).then_some(self.bytes.as_slice())
    }
}

#[test]
fn malformed_weights_fail_with_the_tensor_name() {
    let (name, shape) = contracts().remove(0);
    let mut source = Source {
        info: TensorInfo {
            name: name.clone(),
            dims: shape.iter().rev().map(|&n| n as u64).collect(),
            ggml_type: GGMLType::F32,
            offset: 0,
        },
        bytes: vec![0; shape.iter().product::<usize>() * 4],
    };
    let config = serde_json::from_str(CONFIG).unwrap();
    source.info.dims[0] = 2;
    let load = |s: &Source| {
        Model::from_source(s, &config, ComputePolicy::Cpu)
            .err()
            .unwrap()
    };
    assert!(load(&source).contains(&name));
    source.info.dims[0] = 1;
    source.bytes[..4].copy_from_slice(&f32::NAN.to_le_bytes());
    assert!(load(&source).contains("non-finite"));
    source.bytes.truncate(4);
    assert!(load(&source).contains("invalid storage"));
    source.info.ggml_type = GGMLType::F16;
    assert!(load(&source).contains("expected F32"));
}

#[test]
fn audio_validation_happens_before_inference() {
    let model = Model {
        tensors: HashMap::new(),
    };
    for (samples, rate, channels) in [
        (vec![], 16000, 1),
        (vec![0.; 160], 8000, 1),
        (vec![0.; 1000], 16000, 0),
        (vec![0.; 1000], 96000, 1),
        (vec![0.; 1001], 16000, 2),
        (vec![f32::NAN; 1000], 16000, 1),
    ] {
        assert!(model.enhance(&samples, rate, channels).is_err());
    }
    assert!(model.enhance_wav(b"not a wav").is_err());
}

#[test]
fn sampling_rate_scaling_and_fft_roundtrip_preserve_signal() {
    use crate::models::qwen3::asr::audio_processor::RealFft;
    assert_eq!(signal::parameters(22050).unwrap(), (882, 110));
    for rate in [8000, 16000, 22050, 44100, 48000] {
        let (n, hop) = signal::parameters(rate).unwrap();
        let input: Vec<f32> = (0..n)
            .map(|i| (i as f32 * 0.23).sin() * 0.3 + (i as f32 * 0.71).cos() * 0.1)
            .collect();
        let mut fft = RealFft::new(n).unwrap();
        let mut bins = vec![[0.0; 2]; n / 2 + 1];
        fft.complex(&input, &mut bins);
        let mut restored = vec![0.0; n];
        fft.inverse(&bins, &mut restored);
        let max = input
            .iter()
            .zip(&restored)
            .map(|(a, b)| (a - b).abs())
            .fold(0.0, f32::max);
        assert!(max < 2e-6, "rate={rate} max={max}");
        let samples: Vec<_> = input.iter().cycle().take(5 * n + 13).copied().collect();
        let (mag, phase, t, f) = signal::stft(&samples, rate).unwrap();
        let reconstructed = signal::istft(&mag, &phase, t, f, samples.len(), rate).unwrap();
        let natural = samples.len() / hop * hop;
        let max = samples[..natural]
            .iter()
            .zip(&reconstructed)
            .map(|(a, b)| (a - b).abs())
            .fold(0.0, f32::max);
        assert!(max < 2e-6, "rate={rate} max={max}");
        assert!(reconstructed[natural..].iter().all(|&v| v == 1e-8));
    }
}

#[test]
#[ignore = "requires RMI_REUSE_MODEL and RMI_REUSE_ORACLE generated by tools/oracle/nemotron_reuse/reference.py"]
fn official_spectral_inference_matches_with_numerical_tolerances() {
    let root = std::path::PathBuf::from(std::env::var("RMI_REUSE_ORACLE").unwrap());
    let model = Model::load(
        Path::new(&std::env::var("RMI_REUSE_MODEL").unwrap()),
        ComputePolicy::Cpu,
    )
    .unwrap();
    let manifest: serde_json::Value =
        serde_json::from_slice(&std::fs::read(root.join("manifest.json")).unwrap()).unwrap();
    let read = |row: &serde_json::Value| -> Vec<f32> {
        std::fs::read(root.join(row["file"].as_str().unwrap()))
            .unwrap()
            .chunks_exact(4)
            .map(|v| f32::from_le_bytes(v.try_into().unwrap()))
            .collect()
    };
    // Isolate network/ISTFT accuracy from FFT phase branch-cut sensitivity.
    for case in manifest["cases"].as_array().unwrap() {
        let trace = case["trace"].as_array().unwrap();
        assert_eq!(trace.len() % 36, 0);
        for part in trace.chunks_exact(36) {
            let mag = read(&part[0]);
            let phase = read(&part[1]);
            let t = part[0]["shape"][0].as_u64().unwrap() as usize;
            let f = part[0]["shape"][1].as_u64().unwrap() as usize;
            let expected = read(&part[35]);
            let (mag, phase) = model.forward(&mag, &phase, t, f);
            let actual = signal::istft(
                &mag,
                &phase,
                t,
                f,
                expected.len(),
                case["sample_rate"].as_u64().unwrap() as u32,
            )
            .unwrap();
            let max = actual
                .iter()
                .zip(&expected)
                .map(|(a, b)| (a - b).abs())
                .fold(0., f32::max);
            let rmse = (actual
                .iter()
                .zip(&expected)
                .map(|(a, b)| f64::from(a - b).powi(2))
                .sum::<f64>()
                / actual.len() as f64)
                .sqrt();
            eprintln!("{} max_abs={max:.8e} rmse={rmse:.8e}", case["name"]);
            assert!(max <= 5e-4 && rmse <= 5e-5, "{}", case["name"]);
        }
    }
}
